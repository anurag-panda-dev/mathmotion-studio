"""Trusted Manim scene generation (stage 11) — data in, code out.

The compiler turns a validated :class:`~app.schemas.scene.SceneDocument`
into a standalone ``generated_scene.py`` file plus the
:class:`~app.rendering.layouts.RenderPlan` the worker needs to invoke Manim.

Security invariant (``docs/SECURITY.md`` section 3): **no text from the
scene is ever interpolated into executable Python.** The whole document is
serialized to JSON and embedded as a single ``json.loads(<string literal>)``
call — the JSON string is produced by :func:`json.dumps` and inlined with
:func:`repr`, so it is a literal, never code. All the "behavior" lives in
the trusted :mod:`app.rendering.manim_runtime` module, which is imported,
not generated.
"""

from __future__ import annotations

import json
from dataclasses import dataclass

from app.rendering.layouts import RenderPlan, build_render_plan
from app.schemas.scene import SCENE_FORMAT_VERSION, SceneDocument

# The generated file is intentionally tiny: it carries the payload and
# delegates every decision to the trusted runtime.
_TEMPLATE = '''"""Generated by MathMotion Studio — do not edit.

Scene format {fmt_version}. This file embeds the validated lesson as JSON
data and plays it through the trusted runtime. It contains no interpolated
scene text: every value below is a data literal produced by the compiler.
"""

from __future__ import annotations

import json

from manim import Scene, config as manim_config

# Frame geometry and frame rate are fixed from the render plan so the
# scene units and pixel grid agree (SCENE_FORMAT_SPEC.md section 7.1).
manim_config.frame_height = {frame_height!r}
manim_config.frame_width = {frame_width!r}
manim_config.pixel_height = {pixel_height!r}
manim_config.pixel_width = {pixel_width!r}
manim_config.frame_rate = {frame_rate!r}

from app.rendering.manim_runtime import build_scene  # noqa: E402

PAYLOAD = json.loads({payload_literal})


class Lesson(Scene):
    """Auto-generated lesson scene (single class, per MASTER-PROMPT.md section 8)."""

    def construct(self) -> None:
        build_scene(self, PAYLOAD)
'''


@dataclass(frozen=True)
class CompiledScene:
    """Result of compiling one document: source text plus the render plan."""

    source: str
    plan: RenderPlan
    scene_count: int
    total_duration_s: float


def compile_document(
    document: SceneDocument,
    *,
    aspect_ratio: str | None = None,
    quality: str = "standard",
) -> CompiledScene:
    """Generate the trusted Manim source for a validated document.

    ``aspect_ratio`` defaults to the lesson's own setting; ``quality``
    selects the resolution/frame-rate tier (preview/standard/high).
    """
    lesson = document.lesson
    ratio = aspect_ratio or lesson.aspect_ratio
    plan = build_render_plan(ratio, quality)

    payload = document.to_payload()
    payload["scene_format_version"] = SCENE_FORMAT_VERSION
    # json.dumps -> a JSON *string*; json.dumps of *that* -> a quoted Python
    # literal, and prefixing b makes it a *bytes* literal, safe to inline as
    # source code. Emitting bytes rather than str is essential: json.loads
    # decodes a bytes payload as UTF-8 itself, so non-ASCII content
    # (superscripts, degrees, accents) can never be mangled by the render
    # subprocess's locale/console codepage. No scene text is ever interpolated
    # as code (docs/SECURITY.md section 3).
    payload_literal = "b" + json.dumps(json.dumps(payload, ensure_ascii=False))

    source = _TEMPLATE.format(
        fmt_version=SCENE_FORMAT_VERSION,
        frame_height=plan.frame_height,
        frame_width=plan.frame_width,
        pixel_height=plan.resolution[1],
        pixel_width=plan.resolution[0],
        frame_rate=plan.frame_rate,
        payload_literal=payload_literal,
    )

    total = sum(
        float(scene.duration or 0.0) for scene in document.scenes if scene.duration is not None
    )
    return CompiledScene(
        source=source,
        plan=plan,
        scene_count=len(document.scenes),
        total_duration_s=round(total, 2),
    )


def compile_bytes(document: SceneDocument, **kwargs) -> bytes:  # noqa: ANN003
    """UTF-8 encoded generated source (convenience for file writers)."""
    return compile_document(document, **kwargs).source.encode("utf-8")
