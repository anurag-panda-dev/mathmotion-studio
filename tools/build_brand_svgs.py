#!/usr/bin/env python3
"""Generate the brand SVGs in branding/ from the sources in assets/.

Why this exists
---------------
The wordmark and mark in branding/*.svg must match the raster masters
pixel-for-pixel, and the trajectory must be a separate colorable part.
The potrace trace supplied in assets/cleanvector-sample.svg has perfect
outlines but is monochrome: its mark silhouette merges rings, dots and
trajectory into one contour, so it cannot be color-split. This script
therefore combines two sources:

  1. assets/cleanvector-sample.svg  - potrace outlines for the ink layer
     (mark silhouette + MATHMOTION/STUDIO letterforms), used verbatim.
  2. assets/mathmotion_logo_light.png / assets/mathmotion_app_icon.png -
     colour-segmented (violet / ivory masks), re-traced here with the
     potrace algorithm (pure-Python port "potracer") to produce the
     separate violet-trajectory and icon layers.

Outputs (committed to the repository, regenerate only when sources change):
  branding/logo-primary.svg      light lockup: ink navy + violet trajectory
  branding/logo-dark.svg         dark lockup (500x155, traced from the dark master:
                                 mark violet, letters ivory - not a recolor of the light file)
  branding/logo-monochrome.svg   one color, inherits currentColor
  branding/logo-symbol.svg       mark only (light colors), cropped viewBox
  branding/app-icon.svg          512x512 app icon traced from the icon raster
  branding/favicon.svg           same composition at 256x256

Requirements: numpy, Pillow, potracer   (pip install potracer)
Usage:        python tools/build_brand_svgs.py
"""
from __future__ import annotations

import os
import re
import xml.etree.ElementTree as ET

import numpy as np
from PIL import Image

import potrace

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(REPO, "assets")
BRANDING = os.path.join(REPO, "branding")

NAVY = "#061830"
VIOLET = "#6A4AEE"
IVORY = "#F1F3EA"

SVG_NS = "http://www.w3.org/2000/svg"
PROVENANCE = (
    "Generated by tools/build_brand_svgs.py - do not edit by hand.\n"
    "    Ink outlines: potrace trace of assets/mathmotion_logo_light.png\n"
    "    (assets/cleanvector-sample.svg); violet/ivory layers: colour masks\n"
    "    re-traced from the raster masters. Provenance: branding/assets-manifest.md."
)


# ---------------------------------------------------------------- sample load
def load_sample():
    """Return (mark_path_d, [letter_path_d...], potrace_transform) from the supplied potrace file."""
    tree = ET.parse(os.path.join(ASSETS, "cleanvector-sample.svg"))
    root = tree.getroot()
    group = root.find(f"{{{SVG_NS}}}g")
    transform = group.get("transform")
    paths = group.findall(f"{{{SVG_NS}}}path")
    if len(paths) != 17:
        raise SystemExit(f"expected 17 paths in sample (1 mark + 16 letters), got {len(paths)}")
    mark_d = paths[0].get("d")
    letter_d = [p.get("d") for p in paths[1:]]
    return mark_d, letter_d, transform


# ------------------------------------------------------------------ tracing
def raster(path: str) -> np.ndarray:
    return np.asarray(Image.open(path).convert("RGB")).astype(int)


def violet_mask(rgb: np.ndarray) -> np.ndarray:
    r, g, b = rgb[..., 0], rgb[..., 1], rgb[..., 2]
    return (b >= np.maximum(r, g) + 25) & (b >= 110)


def ivory_mask(rgb: np.ndarray) -> np.ndarray:
    r, g, b = rgb[..., 0], rgb[..., 1], rgb[..., 2]
    return (
        (r > 190)
        & (g > 190)
        & (b > 175)
        & (np.max(rgb, axis=-1) - np.min(rgb, axis=-1) < 45)
    )


def trace(mask: np.ndarray) -> str:
    """Trace a boolean mask into one SVG path-data string (evenodd-friendly).

    Parameter notes (measured against the masters, see assets-manifest.md):
    alphamax 1.33 + opttolerance 0.4 - default potrace params (1.0/0.2) mangle
    the dark master's small letterforms into spiky blobs; the smoothed settings
    track the masters best (mean abs pixel diff 7.7 vs 9.6 dark, 8.8 vs 14.2 icon).
    No mask dilation: dilating the icon's violet layer by 1px only thickened the
    frame/trajectory away from the master (no seam artifacts were observed).
    """
    # potracer inverts its input internally: pass ~mask so the True region is traced.
    # The input MUST be a bool array (non-bool is thresholded at >127.5 and would
    # collapse 0/1 masks to nothing).
    bmp = potrace.Bitmap(~mask.astype(bool))
    path = bmp.trace(turdsize=4, alphamax=1.33, opticurve=True, opttolerance=0.4)
    parts: list[str] = []

    def emit(curves):
        for curve in curves or []:
            pt = curve.start_point
            parts.append(f"M{pt.x:.1f} {pt.y:.1f}")
            for seg in curve.segments:
                end = seg.end_point
                if seg.is_corner:
                    parts.append(f"L{end.x:.1f} {end.y:.1f}")
                else:
                    parts.append(
                        f"C{seg.c1.x:.1f} {seg.c1.y:.1f} {seg.c2.x:.1f} {seg.c2.y:.1f} "
                        f"{end.x:.1f} {end.y:.1f}"
                    )
            parts.append("Z")
            emit(curve.children)

    emit(path.curves)
    return "".join(parts)


# ------------------------------------------------------------------ emitters
def wrap(viewbox: str, title: str, body: str, width: int | None = None) -> str:
    w_attr = f' width="{width}" height="{int(width * int(viewbox.split()[3]) / int(viewbox.split()[2]))}"' if width else ""
    return (
        f'<svg xmlns="{SVG_NS}" viewBox="{viewbox}"{w_attr} role="img" aria-labelledby="t">\n'
        f"  <title id=\"t\">{title}</title>\n"
        f"  <!--\n    {PROVENANCE}\n  -->\n"
        f"{body}"
        f"</svg>\n"
    )


def ink_group(mark_d: str, letter_ds: list[str], transform: str, fill: str) -> str:
    letters = "".join(f'    <path fill="{fill}" d="{d}"/>\n' for d in letter_ds)
    return (
        f'  <g transform="{transform}" fill="{fill}">\n'
        f'    <path d="{mark_d}"/>\n'
        f"{letters}"
        f"  </g>\n"
    )


def write(name: str, content: str) -> None:
    ET.fromstring(content)  # well-formedness gate
    with open(os.path.join(BRANDING, name), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(content)
    print(f"  wrote {name} ({len(content)} bytes)")


def main() -> int:
    mark_d, letter_ds, transform = load_sample()

    logo = raster(os.path.join(ASSETS, "mathmotion_logo_light.png"))
    dark = raster(os.path.join(ASSETS, "mathmotion_logo_dark.png"))
    icon = raster(os.path.join(ASSETS, "mathmotion_app_icon.png"))
    logo_w, logo_h = Image.open(os.path.join(ASSETS, "mathmotion_logo_light.png")).size
    dark_w, dark_h = Image.open(os.path.join(ASSETS, "mathmotion_logo_dark.png")).size
    icon_w, icon_h = Image.open(os.path.join(ASSETS, "mathmotion_app_icon.png")).size

    logo_violet = trace(violet_mask(logo))
    dark_violet = trace(violet_mask(dark))          # mark on navy background
    dark_ivory = trace(ivory_mask(dark))            # wordmark letters
    icon_violet = trace(violet_mask(icon))          # frame + trajectory (no dilation: see trace())
    icon_ivory = trace(ivory_mask(icon))

    # mark-only crop box for logo-symbol.svg (ink left of the wordmark, padded)
    ink = logo.sum(axis=-1) < 420
    mark_region = (ink | violet_mask(logo))[:, :325]
    ys, xs = np.nonzero(mark_region)
    x0, y0, x1, y1 = xs.min() - 4, ys.min() - 4, xs.max() + 5, ys.max() + 5

    body = ink_group(mark_d, letter_ds, transform, NAVY)
    body += f'  <path fill="{VIOLET}" d="{logo_violet}"/>\n'
    write("logo-primary.svg", wrap("0 0 885 225", "MathMotion Studio — primary logo (light backgrounds)", body))

    # Dark variant is traced from ITS OWN raster (500x155): the dark master has
    # different margins/proportions than the light one, so it is not a recolor.
    body = (
        f'  <g fill-rule="evenodd">\n'
        f'    <path fill="{VIOLET}" d="{dark_violet}"/>\n'
        f'    <path fill="{IVORY}" d="{dark_ivory}"/>\n'
        f"  </g>\n"
    )
    write("logo-dark.svg", wrap(f"0 0 {dark_w} {dark_h}", "MathMotion Studio — logo for dark backgrounds", body))

    body = ink_group(mark_d, letter_ds, transform, "currentColor")
    write("logo-monochrome.svg", wrap("0 0 885 225", "MathMotion Studio — monochrome logo", body))

    body = (
        f'  <g transform="translate({-x0},{-y0})">\n'
        f'    <g transform="{transform}" fill="{NAVY}">\n'
        f'      <path d="{mark_d}"/>\n'
        f"    </g>\n"
        f'    <path fill="{VIOLET}" d="{logo_violet}"/>\n'
        f"  </g>\n"
    )
    write(
        "logo-symbol.svg",
        wrap(f"0 0 {x1 - x0} {y1 - y0}", "MathMotion Studio symbol", body),
    )

    # App icon / favicon: navy plate + traced ivory orbits + violet frame & trajectory.
    scale = 512 / icon_w
    dy = (512 - icon_h * scale) / 2
    icon_body = (
        f'  <rect width="512" height="512" fill="{NAVY}"/>\n'
        f'  <g transform="translate(0,{dy:.1f}) scale({scale:.5f})" fill-rule="evenodd">\n'
        f'    <path fill="{IVORY}" d="{icon_ivory}"/>\n'
        f'    <path fill="{VIOLET}" d="{icon_violet}"/>\n'
        f"  </g>\n"
    )
    write("app-icon.svg", wrap("0 0 512 512", "MathMotion Studio app icon", icon_body))

    fscale = 256 / icon_w
    fdy = (256 - icon_h * fscale) / 2
    fav_body = (
        f'  <rect width="256" height="256" fill="{NAVY}"/>\n'
        f'  <g transform="translate(0,{fdy:.1f}) scale({fscale:.5f})" fill-rule="evenodd">\n'
        f'    <path fill="{IVORY}" d="{icon_ivory}"/>\n'
        f'    <path fill="{VIOLET}" d="{icon_violet}"/>\n'
        f"  </g>\n"
    )
    write("favicon.svg", wrap("0 0 256 256", "MathMotion Studio favicon", fav_body))

    print(f"symbol crop box: ({x0},{y0})-({x1},{y1})  |  logo {logo_w}x{logo_h}, icon {icon_w}x{icon_h}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
